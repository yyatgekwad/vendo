function renderVerticalBarChart(container, items, valueFor, labelFor, shareTotal, allowNegative = false) {
  if (!(container instanceof HTMLElement)) return;
  container.replaceChildren();
  if (!items.length) {
    const empty = document.createElement("p");
    empty.className = "overview-chart-empty";
    empty.textContent = inventoryText("overview-chart-empty");
    container.append(empty);
    return;
  }
  const maximum = Math.max(1, ...items.map((item) => Math.abs(valueFor(item))));
  items.forEach((item) => {
    const value = valueFor(item);
    const row = document.createElement("div");
    row.className = "overview-chart-row";
    const label = document.createElement("span");
    label.className = "overview-chart-label";
    label.textContent = labelFor(item);
    label.title = label.textContent;
    const track = document.createElement("span");
    track.className = "overview-chart-track";
    const bar = document.createElement("span");
    bar.className = `overview-chart-bar${allowNegative && value < 0 ? " is-negative" : ""}`;
    bar.style.height = `${Math.abs(value) / maximum * 100}%`;
    track.append(bar);
    const amount = document.createElement("strong");
    amount.className = "overview-chart-value";
    amount.textContent = formatAccountAmount(value);
    const share = document.createElement("span");
    share.className = "overview-chart-share";
    const arrow = document.createElement("span");
    arrow.className = "overview-chart-arrow";
    arrow.setAttribute("aria-hidden", "true");
    arrow.textContent = value < 0 ? "↓" : "↑";
    const percentage = document.createElement("span");
    percentage.textContent = `${(shareTotal > 0 ? Math.abs(value) / shareTotal * 100 : 0).toLocaleString(currentLanguage === "ar" ? "ar" : "en", {
      maximumFractionDigits: 1
    })}%`;
    share.append(arrow, percentage);
    const metrics = document.createElement("span");
    metrics.className = "overview-chart-metrics";
    metrics.append(amount, share);
    row.append(metrics, track, label);
    container.append(row);
  });
}

function renderOverviewCharts(deliveredOrders) {
  const stockChart = document.querySelector("[data-overview-stock-chart]");
  const salesChart = document.querySelector("[data-overview-sales-chart]");
  const totalUnits = inventoryProducts.reduce((sum, product) => sum + product.quantity, 0);
  const totalUnitsElement = document.querySelector("[data-overview-stock-units]");
  const productCountElement = document.querySelector("[data-overview-product-count]");
  const salesTotalElement = document.querySelector("[data-overview-sales-total]");
  if (totalUnitsElement) totalUnitsElement.textContent = formatAccountAmount(totalUnits);
  if (productCountElement) productCountElement.textContent = formatAccountAmount(inventoryProducts.length);
  const totalSales = deliveredOrders.reduce((sum, order) => sum + order.price * order.quantity, 0);
  if (salesTotalElement) salesTotalElement.textContent = formatAccountAmount(totalSales);
  const stockItems = [...inventoryProducts]
    .sort((a, b) => b.quantity - a.quantity || a.name.localeCompare(b.name))
    .slice(0, 8);
  const salesItems = [...deliveredOrders]
    .sort((a, b) => b.createdAt.localeCompare(a.createdAt))
    .slice(0, 8);
  renderVerticalBarChart(
    stockChart,
    stockItems,
    (product) => product.quantity,
    (product) => product.name,
    totalUnits
  );
  renderVerticalBarChart(
    salesChart,
    salesItems,
    (order) => order.price * order.quantity,
    (order) => `${order.product} · ${order.customer}`,
    totalSales
  );
}

function renderOrderPages() {
  const orders = Array.isArray(userVendoData?.orders) ? userVendoData.orders : [];
  const liveOrders = orders.filter((order) => order.status !== "cancelled");
  const deliveredOrders = orders.filter((order) => order.status === "delivered");
  const revenue = deliveredOrders.reduce((sum, order) => sum + order.price * order.quantity, 0);
  const cost = deliveredOrders.reduce((sum, order) => sum + order.cost * order.quantity, 0);

  const putText = (selector, text) => {
    const node = document.querySelector(selector);
    if (node) node.textContent = text;
  };
  putText("[data-orders-total]", String(orders.length));
  putText("[data-orders-open]", String(orders.filter((order) => ["new", "processing", "shipped"].includes(order.status)).length));
  putText("[data-orders-revenue]", formatAccountAmount(revenue));
  putText("[data-profits-revenue]", formatAccountAmount(revenue));
  putText("[data-profits-cost]", formatAccountAmount(cost));
  putText("[data-profits-net]", formatAccountAmount(revenue - cost));
  renderOverviewCharts(deliveredOrders);

  const ordersRows = document.querySelector("[data-orders-rows]");
  if (ordersRows instanceof HTMLElement) {
    ordersRows.replaceChildren();
    [...orders].sort((a, b) => b.createdAt.localeCompare(a.createdAt)).forEach((order) => {
      const row = document.createElement("tr");
      row.append(
        createInventoryCell(order.customer, "inventory-product-name"),
        createInventoryCell(order.product),
        createInventoryCell(String(order.quantity)),
        createInventoryCell(formatAccountAmount(order.price * order.quantity)),
        createInventoryCell(orderStatusLabel(order.status))
      );
      const actions = document.createElement("td");
      const remove = document.createElement("button");
      remove.type = "button";
      remove.className = "inventory-action delete";
      remove.textContent = inventoryText("inventory-delete");
      remove.setAttribute("aria-label", `${inventoryText("inventory-delete")}: ${order.product}`);
      remove.addEventListener("click", async () => {
        if (!window.confirm(inventoryText("order-delete-confirm"))) return;
        const next = orders.filter((item) => item.id !== order.id);
        if (await saveOrders(next, "order-deleted")) renderOrderPages();
      });
      actions.append(remove);
      row.append(actions);
      ordersRows.append(row);
    });
    const empty = document.querySelector("[data-orders-empty]");
    if (empty instanceof HTMLElement) empty.hidden = orders.length > 0;
  }

  const customerMap = new Map();
  liveOrders.forEach((order) => {
    const key = order.phone.trim().toLowerCase();
    const customer = customerMap.get(key) || { name: order.customer, phone: order.phone, count: 0, spend: 0 };
    customer.count += 1;
    customer.spend += order.price * order.quantity;
    customerMap.set(key, customer);
  });
  const customers = [...customerMap.values()];
  putText("[data-customers-total]", String(customers.length));
  putText("[data-customers-orders]", String(liveOrders.length));
  putText("[data-customers-spend]", formatAccountAmount(liveOrders.reduce((sum, order) => sum + order.price * order.quantity, 0)));
  const customersRows = document.querySelector("[data-customers-rows]");
  if (customersRows instanceof HTMLElement) {
    customersRows.replaceChildren();
    customers.sort((a, b) => a.name.localeCompare(b.name)).forEach((customer) => {
      const row = document.createElement("tr");
      row.append(
        createInventoryCell(customer.name, "inventory-product-name"),
        createInventoryCell(customer.phone),
        createInventoryCell(String(customer.count)),
        createInventoryCell(formatAccountAmount(customer.spend))
      );
      customersRows.append(row);
    });
    const empty = document.querySelector("[data-customers-empty]");
    if (empty instanceof HTMLElement) empty.hidden = customers.length > 0;
  }

  const awaiting = orders.filter((order) => ["new", "processing"].includes(order.status)).length;
  const inDelivery = orders.filter((order) => order.status === "shipped").length;
  putText("[data-shipping-open]", String(awaiting));
  putText("[data-shipping-progress]", String(inDelivery));
  putText("[data-shipping-delivered]", String(deliveredOrders.length));
  const shippingRows = document.querySelector("[data-shipping-rows]");
  if (shippingRows instanceof HTMLElement) {
    shippingRows.replaceChildren();
    orders.filter((order) => order.status !== "cancelled").forEach((order) => {
      const row = document.createElement("tr");
      row.append(
        createInventoryCell(order.customer, "inventory-product-name"),
        createInventoryCell(order.phone),
        createInventoryCell(order.product)
      );
      const statusCell = createInventoryCell(orderStatusLabel(order.status));
      row.append(statusCell);
      const updateCell = document.createElement("td");
      const select = document.createElement("select");
      select.className = "account-status-select";
      select.setAttribute("aria-label", `${inventoryText("shipping-update")}: ${order.customer}`);
      orderStatuses.forEach((status) => {
        const option = document.createElement("option");
        option.value = status;
        option.textContent = orderStatusLabel(status);
        option.selected = status === order.status;
        select.append(option);
      });
      select.addEventListener("change", async () => {
        const next = orders.map((item) => item.id === order.id ? { ...item, status: select.value } : item);
        if (await saveOrders(next, "shipping-updated")) renderOrderPages();
        else select.value = order.status;
      });
      updateCell.append(select);
      row.append(updateCell);
      shippingRows.append(row);
    });
    const empty = document.querySelector("[data-shipping-empty]");
    if (empty instanceof HTMLElement) empty.hidden = orders.every((order) => order.status === "cancelled");
  }

  const profitRows = document.querySelector("[data-profits-rows]");
  const profitChart = document.querySelector("[data-profits-chart]");
  const orderProfits = deliveredOrders.map((order) => ({
    ...order,
    profit: (order.price - order.cost) * order.quantity
  }));
  const profitShareTotal = orderProfits.reduce((sum, order) => sum + Math.abs(order.profit), 0);
  renderVerticalBarChart(
    profitChart,
    [...orderProfits].sort((a, b) => b.createdAt.localeCompare(a.createdAt)).slice(0, 8),
    (order) => order.profit,
    (order) => `${order.product} · ${order.customer}`,
    profitShareTotal,
    true
  );
  if (profitRows instanceof HTMLElement) {
    profitRows.replaceChildren();
    orderProfits.forEach((order) => {
      const row = document.createElement("tr");
      row.append(
        createInventoryCell(order.customer),
        createInventoryCell(order.product),
        createInventoryCell(String(order.quantity)),
        createInventoryCell(formatAccountAmount(order.price * order.quantity)),
        createInventoryCell(formatAccountAmount(order.cost * order.quantity)),
        createInventoryCell(formatAccountAmount(order.profit))
      );
      profitRows.append(row);
    });
    const empty = document.querySelector("[data-profits-empty]");
    if (empty instanceof HTMLElement) empty.hidden = deliveredOrders.length > 0;
  }
}

async function saveOrders(nextOrders, messageKey) {
  try {
    const validOrders = validateOrders(nextOrders);
    persistLocalVendoData({ ...userVendoData, orders: validOrders });
    renderOrderPages();
    const message = document.querySelector("[data-orders-message], [data-shipping-message]");
    if (message instanceof HTMLElement) message.textContent = inventoryText(messageKey);
    return true;
  } catch (error) {
    console.error("Could not save orders on this device.", error);
    const message = document.querySelector("[data-orders-message], [data-shipping-message]");
    if (message instanceof HTMLElement) message.textContent = inventoryText("local-save-error");
    return false;
  }
}

function renderInventory() {
  if (!(inventoryRows instanceof HTMLElement)) return;
  const query = inventorySearch instanceof HTMLInputElement ? inventorySearch.value.trim().toLocaleLowerCase() : "";
  const showLowStock = inventoryFilter instanceof HTMLSelectElement && inventoryFilter.value === "low";
  const visibleProducts = inventoryProducts.filter((product) => {
    const matchesQuery = !query || `${product.name} ${product.sku}`.toLocaleLowerCase().includes(query);
    return matchesQuery && (!showLowStock || product.quantity <= 5);
  });
  const totalUnits = inventoryProducts.reduce((sum, product) => sum + product.quantity, 0);
  const lowStockCount = inventoryProducts.filter((product) => product.quantity <= 5).length;
  const totalElement = document.querySelector("[data-inventory-total]");
  const unitsElement = document.querySelector("[data-inventory-units]");
  const lowElement = document.querySelector("[data-inventory-low]");
  if (totalElement) totalElement.textContent = String(inventoryProducts.length);
  if (unitsElement) unitsElement.textContent = String(totalUnits);
  if (lowElement) lowElement.textContent = String(lowStockCount);
  renderOverviewCharts(Array.isArray(userVendoData?.orders)
    ? userVendoData.orders.filter((order) => order.status === "delivered")
    : []);

  inventoryRows.replaceChildren();
  visibleProducts.forEach((product) => {
    const row = document.createElement("tr");
    const nameCell = createInventoryCell(product.name, "inventory-product-name");
    const skuCell = createInventoryCell(product.sku || "—", "inventory-product-sku");
    const priceCell = createInventoryCell(new Intl.NumberFormat(currentLanguage === "ar" ? "ar" : "en", { maximumFractionDigits: 2 }).format(product.price));
    const quantityCell = createInventoryCell(new Intl.NumberFormat(currentLanguage === "ar" ? "ar" : "en").format(product.quantity));
    const statusCell = document.createElement("td");
    const status = getInventoryStatus(product.quantity);
    const badge = document.createElement("span");
    badge.className = `inventory-status ${status.className}`;
    badge.textContent = inventoryText(status.label);
    statusCell.append(badge);

    const actionsCell = document.createElement("td");
    const actions = document.createElement("div");
    actions.className = "inventory-actions";
    const editButton = document.createElement("button");
    editButton.type = "button";
    editButton.className = "inventory-action";
    editButton.textContent = inventoryText("inventory-edit");
    editButton.setAttribute("aria-label", `${inventoryText("inventory-edit")}: ${product.name}`);
    editButton.addEventListener("click", () => openInventoryForm(product));
    const deleteButton = document.createElement("button");
    deleteButton.type = "button";
    deleteButton.className = "inventory-action delete";
    deleteButton.textContent = inventoryText("inventory-delete");
    deleteButton.setAttribute("aria-label", `${inventoryText("inventory-delete")}: ${product.name}`);
    deleteButton.addEventListener("click", () => {
      if (!window.confirm(inventoryText("inventory-delete-confirm"))) return;
      saveInventory(inventoryProducts.filter((item) => item.id !== product.id), "inventory-product-deleted");
    });
    actions.append(editButton, deleteButton);
    actionsCell.append(actions);
    row.append(nameCell, skuCell, priceCell, quantityCell, statusCell, actionsCell);
    inventoryRows.append(row);
  });

  if (inventoryEmpty instanceof HTMLElement) {
    const isEmpty = visibleProducts.length === 0;
    inventoryEmpty.hidden = !isEmpty;
    const title = inventoryEmpty.querySelector("h3");
    const description = inventoryEmpty.querySelector("p");
    const addButton = inventoryEmpty.querySelector("button");
    if (title && description && addButton) {
      if (inventoryProducts.length === 0) {
        title.textContent = inventoryText("inventory-empty-title");
        description.textContent = inventoryText("inventory-empty-description");
        addButton.hidden = false;
      } else {
        title.textContent = inventoryText("inventory-no-results");
        description.textContent = "";
        addButton.hidden = true;
      }
    }
  }
}

function openInventoryForm(product = null) {
  if (!(inventoryModal instanceof HTMLElement) || !(inventoryForm instanceof HTMLFormElement)) return;
  editingProductId = product?.id || null;
  inventoryForm.reset();
  const nameField = inventoryForm.elements.namedItem("name");
  const skuField = inventoryForm.elements.namedItem("sku");
  const priceField = inventoryForm.elements.namedItem("price");
  const quantityField = inventoryForm.elements.namedItem("quantity");
  if (product && nameField instanceof HTMLInputElement && skuField instanceof HTMLInputElement && priceField instanceof HTMLInputElement && quantityField instanceof HTMLInputElement) {
    nameField.value = product.name;
    skuField.value = product.sku;
    priceField.value = String(product.price);
    quantityField.value = String(product.quantity);
  }
  const title = document.querySelector("#inventory-dialog-title");
  if (title) title.textContent = inventoryText(product ? "inventory-edit-title" : "inventory-add-title");
  setInventoryMessage("");
  inventoryModal.hidden = false;
  nameField instanceof HTMLInputElement && nameField.focus();
}

function closeInventoryForm() {
  if (!(inventoryModal instanceof HTMLElement)) return;
  inventoryModal.hidden = true;
  editingProductId = null;
}

