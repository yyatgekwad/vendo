inventoryForm?.addEventListener("submit", async (event) => {
  event.preventDefault();
  if (!(inventoryForm instanceof HTMLFormElement)) return;
  const formData = new FormData(inventoryForm);
  const name = String(formData.get("name") || "").trim();
  const sku = String(formData.get("sku") || "").trim();
  const price = Number(formData.get("price"));
  const quantity = Number(formData.get("quantity"));
  if (!name || !Number.isFinite(price) || price < 0 || !Number.isInteger(quantity) || quantity < 0) {
    setInventoryMessage("inventory-validation-error");
    return;
  }
  const existingProduct = inventoryProducts.find((product) => product.id === editingProductId);
  const product = {
    id: existingProduct?.id || `${Date.now()}-${Math.random().toString(36).slice(2, 8)}`,
    name,
    sku,
    price,
    quantity
  };
  const nextProducts = existingProduct
    ? inventoryProducts.map((item) => item.id === editingProductId ? product : item)
    : [...inventoryProducts, product];
  if (await saveInventory(nextProducts, existingProduct ? "inventory-product-updated" : "inventory-product-added")) closeInventoryForm();
});

