function getAuthErrorMessage(error) {
  const message = String(error?.message || "");
  const normalized = message.toLowerCase();
  if (normalized.includes("invalid login credentials")) {
    return translations[currentLanguage]["account-login-invalid"];
  }
  if (normalized.includes("email not confirmed")) {
    return translations[currentLanguage]["account-confirmation-required"];
  }
  if (normalized.includes("already registered")) {
    return translations[currentLanguage]["account-already-exists"];
  }
  if (normalized.includes("failed to fetch") || normalized.includes("network")) {
    return translations[currentLanguage]["account-service-error"];
  }
  if (normalized.includes("provider is not enabled") || normalized.includes("unsupported provider")) {
    return translations[currentLanguage]["google-setup-required"];
  }
  return message || translations[currentLanguage]["account-service-error"];
}

